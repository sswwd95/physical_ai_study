# 이미지를 x축, y축 방향으로 이동함
#
# OpenCV에서는 이동도 Affine 변환의 한 종류임
#
# [실습 목표]
# 1. 이미지 이동 개념 이해
# 2. Translation Matrix 생성
# 3. cv2.warpAffine() 재사용
# 4. x, y 방향 이동 결과 확인
#
# [실무에서 자주 하는 실수]
# 실수 1. 이동 후 빈 영역이 생기는 것을 오류로 생각함
#
# 이미지를 오른쪽이나 아래로 이동하면 왼쪽 또는 위쪽에 빈 영역이 발생
#
# 이것은 정상임
#
# 새로 생긴 영역은 기본적으로 검은색으로 채워집니다.
#
# 실수 2. y축 방향을 수학 좌표계처럼 생각함
#
# 일반 수학 좌표계에서는 y가 위로 증가함
#
# 하지만 이미지 좌표계에서는 다음과 같습니다.
#
# x 증가 → 오른쪽
# y 증가 → 아래쪽
#
# 따라서 `move_y = 50`은 위가 아니라 아래로 이동임
#
# [ROS2와 연결되는 포인트]
# 이미지 이동은 로봇 비전에서 직접 자주 쓰이기보다는, Affine 변환과 Perspective 변환을 이해하기 위한 기초임
#
# 하지만 다음 상황에서 사용될 수 있음
#
# 카메라 영상 정렬
# 두 이미지 간 위치 보정
# 센서 캘리브레이션 전처리
# 이미지 증강 데이터 생성
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2
# 이미지 배열 및 수치 계산용 NumPy 불러오기
import numpy as np

# 입력 또는 출력 파일 경로 지정
image_path = "practice_images/sample.jpg"

# 지정 경로의 이미지 읽기 및 NumPy 배열 저장
image = cv2.imread(image_path)

# 이미지 또는 검출 결과 생성 여부 확인
if image is None:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 읽을 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 이미지 배열의 높이, 너비, 채널 수 같은 크기 정보를 가져옵니다.
    height, width = image.shape[:2]

    # move x 변수에 이후 처리에 사용할 값을 저장
    move_x = 100
    # move y 변수에 이후 처리에 사용할 값을 저장
    move_y = 50

    # OpenCV 변환 함수가 요구하는 32비트 실수 형식으로 좌표를 생성
    translation_matrix = np.float32([
        [1, 0, move_x],
        [0, 1, move_y]
    ])

    # 이동·회전·기울이기 같은 Affine 변환을 이미지에 적용
    moved_image = cv2.warpAffine(image, translation_matrix, (width, height))

    # 처리 결과 확인용 OpenCV 창 표시
    cv2.imshow("Original Image", image)
    cv2.imshow("Moved Image", moved_image)

    # 키 입력 대기 및 실시간 영상 갱신
    cv2.waitKey(0)
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
