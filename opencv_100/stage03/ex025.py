# [핵심 주제]
# `cv2.flip()`을 사용하여 이미지를 좌우, 상하, 또는 상하좌우로 뒤집습니다.
#
# 카메라 설치 방향이 반대로 되어 있거나, 웹캠 영상이 거울처럼 보일 때 사용
#
# [실습 목표]
# 1. cv2.flip() 사용법 이해
# 2. 좌우 반전
# 3. 상하 반전
# 4. 상하좌우 반전
#
# [실무에서 자주 하는 실수]
# 실수 1. flipCode 값을 헷갈림
#
# 반드시 다음 표를 기억함
#
# | flipCode | 의미 |
# | --- | --- |
# | 1 | 좌우 반전 |
# | 0 | 상하 반전 |
# | -1 | 상하좌우 반전 |
#
# 실수 2. 카메라 좌표계와 로봇 좌표계를 혼동함
#
# 이미지를 좌우 반전하면 화면에서 객체가 보이는 위치가 변화
#
# 예를 들어 원래 객체가 화면 왼쪽에 있었는데, 좌우 반전 후에는 오른쪽에 보임
#
# 로봇 제어에 연결할 때는 다음 관계를 반드시 확인필요
#
# 이미지 좌표의 왼쪽/오른쪽
# 로봇 기준 좌회전/우회전
#
# [ROS2와 연결되는 포인트]
# 웹캠이나 USB 카메라를 사용할 때 영상이 거울처럼 보이는 경우가 있음
#
# 그럴 때 다음처럼 보정할 수 있음
#
# frame = cv2.flip(frame, 1)
#
# 하지만 로봇 주행 제어에 사용할 때는 무조건 반전하면 안 됨
#
# 화면에서의 좌우와 실제 로봇의 좌우가 바뀌기 때문임
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 입력 또는 출력 파일 경로 지정
image_path = "practice_images/sample.jpg"

# 지정 경로의 이미지 읽기 및 NumPy 배열 저장
image = cv2.imread(image_path)

# 이미지 또는 검출 결과 생성 여부 확인
if image is None:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 읽을 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 이미지를 좌우 또는 상하 방향으로 뒤집습니다.
    flip_horizontal = cv2.flip(image, 1)
    flip_vertical = cv2.flip(image, 0)
    flip_both = cv2.flip(image, -1)

    # 처리 결과 확인용 OpenCV 창 표시
    cv2.imshow("Original Image", image)
    cv2.imshow("Flip Horizontal", flip_horizontal)
    cv2.imshow("Flip Vertical", flip_vertical)
    cv2.imshow("Flip Both", flip_both)

    # 키 입력 대기 및 실시간 영상 갱신
    cv2.waitKey(0)
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
