# ============================================================================
# 노션 원문 학습 설명: 예제 21. 이미지 Resize
# ============================================================================
#
# [핵심 주제]
# `cv2.resize()`를 사용하여 이미지 크기를 변경합니다.
#
# ROS2 카메라 영상은 해상도가 클 수 있음
#
# 예를 들어 1920×1080 이미지를 그대로 처리하면 계산량이 많아집니다.
#
# 그래서 실시간 로봇 비전에서는 이미지를 줄여서 처리하는 경우가 많습니다.
#
# [실습 목표]
# 1. cv2.resize() 사용법 이해
# 2. 이미지 너비와 높이 변경
# 3. 해상도 변경 결과 확인
# 4. 실시간 처리에서 Resize가 필요한 이유 이해
#
# [실무에서 자주 하는 실수]
# 실수 1. width와 height 순서를 반대로 넣음
#
# 다음처럼 쓰면 의도와 다른 크기가 됨
#
# resized_image = cv2.resize(image, (240, 320))
#
# 이 코드는 너비 240, 높이 320임
#
# OpenCV의 `resize()`는 반드시 다음 순서를 사용
#
# cv2.resize(image, (width, height))
#
# 실수 2. 너무 작은 크기로 줄여서 정보 손실
#
# 예를 들어 객체가 작은데 이미지를 너무 줄이면 객체가 사라질 수 있음
#
# 원본: 1280×720
# 변경: 160×90
#
# 실시간 처리는 빨라지지만 작은 장애물, 라인, 표식 검출 성능이 떨어질 수 있음
#
# [ROS2와 연결되는 포인트]
# ROS2 카메라 노드에서는 해상도 조절이 매우 중요
#
# 고해상도 이미지
# 장점: 정보가 많음
# 단점: 처리 속도 느림
#
# 저해상도 이미지
# 장점: 처리 속도 빠름
# 단점: 작은 객체 검출 어려움
#
# 실무에서는 보통 다음처럼 균형을 잡습니다.
#
# 실시간 주행 제어: 320×240 또는 640×480
# 정밀 검사: 1280×720 이상
# 딥러닝 입력: 모델이 요구하는 크기, 예: 640×640
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 입력 또는 출력 파일 경로 지정
image_path = "practice_images/sample.jpg"

# 지정 경로의 이미지 읽기 및 NumPy 배열 저장
image = cv2.imread(image_path)

# 이미지 또는 검출 결과 생성 여부 확인
if image is None:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 읽을 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 이미지의 가로·세로 크기를 원하는 크기로 변경함
    resized_image = cv2.resize(image, (320, 240))

    # 현재 상태 또는 계산 결과의 터미널 출력
    print("원본 이미지 크기:", image.shape)
    print("변경 이미지 크기:", resized_image.shape)

    # 처리 결과 확인용 OpenCV 창 표시
    cv2.imshow("Original Image", image)
    cv2.imshow("Resized Image", resized_image)

    # 키 입력 대기 및 실시간 영상 갱신
    cv2.waitKey(0)
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
