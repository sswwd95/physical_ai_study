#
# [실습 목표]
# 1. 이미지 패딩 개념 이해
# 2. cv2.copyMakeBorder() 사용법 이해
# 3. 검은색 여백 추가
# 4. 비율 유지 Resize와 패딩의 관계 이해
#
# [실무에서 자주 하는 실수]
# 실수 1. 패딩 색상 순서를 RGB로 넣음
#
# OpenCV는 BGR임
#
# 빨간 패딩을 만들고 싶으면 다음처럼 필요
#
# value=(0, 0, 255)
#
# RGB 기준으로 생각해서 `(255, 0, 0)`을 넣으면 파란색이 됨
#
# 실수 2. 패딩 후 좌표계를 보정하지 않음
#
# 이미지 왼쪽에 100픽셀 패딩을 추가하면 원본 객체의 x좌표도 100만큼 이동한 것처럼 보임
#
# 예를 들어 원본 객체 중심이 다음 좌표였다면,
#
# x = 200
# y = 150
#
# 왼쪽 100픽셀, 위쪽 50픽셀 패딩 후에는 다음 좌표가 됨
#
# x = 300
# y = 200
#
# 좌표 기반 로봇 제어에서는 반드시 이 보정을 고려필요
#
# [ROS2와 연결되는 포인트]
# YOLO 같은 딥러닝 모델에서는 입력 크기를 맞추기 위해 비율 유지 Resize + Padding을 자주 사용
#
# 카메라 원본 1280×720
# → 비율 유지 Resize
# → 640×360
# → 위아래 Padding
# → 640×640
# → 모델 입력
#
# 이런 방식을 흔히 Letterbox 처리라고 부릅니다.
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 입력 또는 출력 파일 경로 지정
image_path = "practice_images/sample.jpg"

# 지정 경로의 이미지 읽기 및 NumPy 배열 저장
image = cv2.imread(image_path)

# 이미지 또는 검출 결과 생성 여부 확인
if image is None:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 읽을 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 이미지 바깥쪽에 지정한 방식의 여백을 추가
    padded_image = cv2.copyMakeBorder(
        image,
        top=50,
        bottom=50,
        left=100,
        right=100,
        borderType=cv2.BORDER_CONSTANT,
        value=(0, 0, 0)
    )

    # 현재 상태 또는 계산 결과의 터미널 출력
    print("원본 크기:", image.shape)
    print("패딩 후 크기:", padded_image.shape)

    # 처리 결과 확인용 OpenCV 창 표시
    cv2.imshow("Original Image", image)
    cv2.imshow("Padded Image", padded_image)

    # 키 입력 대기 및 실시간 영상 갱신
    cv2.waitKey(0)
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
