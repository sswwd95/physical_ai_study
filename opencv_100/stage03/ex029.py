# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 입력 또는 출력 파일 경로 지정
image_path = "practice_images/sample.jpg"

# 지정 경로의 이미지 읽기 및 NumPy 배열 저장
image = cv2.imread(image_path)

# 이미지 또는 검출 결과 생성 여부 확인
if image is None:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 읽을 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 가우시안 피라미드 방식으로 이미지 크기를 절반가량 축소함
    down1 = cv2.pyrDown(image)
    down2 = cv2.pyrDown(down1)

    # 현재 상태 또는 계산 결과의 터미널 출력
    print("원본 크기:", image.shape)
    print("1단계 축소:", down1.shape)
    print("2단계 축소:", down2.shape)

    # 처리 결과 확인용 OpenCV 창 표시
    cv2.imshow("Original Image", image)
    cv2.imshow("Pyramid Down 1", down1)
    cv2.imshow("Pyramid Down 2", down2)

    # 키 입력 대기 및 실시간 영상 갱신
    cv2.waitKey(0)
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
