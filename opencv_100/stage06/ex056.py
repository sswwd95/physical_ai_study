# 4. 파일 기반 영상 분석 구조 이해
#
# [준비 파일]
# 다음 경로에 실습용 영상을 준비함
#
# practice_videos/sample.mp4
#
# [실무에서 자주 하는 실수]
# 실수 1. 영상 파일 경로 오류
#
# 이미지와 마찬가지로 비디오도 경로가 틀리면 열리지 않습니다.
#
# 가능하면 영문 경로를 권장함
#
# C:/opencv_practice/practice_videos/sample.mp4
#
# 실수 2. 코덱 문제를 코드 오류로 착각함
#
# 특정 mp4 파일이 OpenCV에서 열리지 않을 수 있음
#
# 이 경우 다른 mp4 파일로 테스트하거나 코덱을 변환필요
#
# [ROS2와 연결되는 포인트]
# 비디오 파일 읽기는 ROS2 카메라 없이 알고리즘을 테스트할 때 유용
#
# 저장된 주행 영상
# → OpenCV로 프레임 읽기
# → 라인 검출 알고리즘 테스트
# → 안정화 후 ROS2 카메라 노드에 적용
#
# 실제 로봇 없이도 영상 기반 알고리즘을 반복 테스트할 수 있음
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 입력 또는 출력 파일 경로 지정
video_path = "practice_videos/sample.mp4"

# 웹캠 번호 또는 동영상 파일을 OpenCV 영상 입력으로 열기
cap = cv2.VideoCapture(video_path)

# 카메라나 동영상 입력이 정상적으로 열렸는지 확인
if not cap.isOpened():
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("비디오 파일을 열 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 조건이 참인 동안 아래 코드를 계속 반복
    while True:
        # 영상에서 프레임 한 장을 읽고, 성공 여부와 이미지 배열을 각각 수신
        ret, frame = cap.read()

        # 필요한 조건이 충족되지 않았을 때의 처리를 시작함
        if not ret:
            # 현재 상태 또는 계산 결과의 터미널 출력
            print("비디오가 끝났거나 프레임을 읽을 수 없습니다.")
            # 현재 반복문을 즉시 종료
            break

        # 처리 결과 확인용 OpenCV 창 표시
        cv2.imshow("Video File", frame)

        # 키 입력 대기 및 실시간 영상 갱신
        if cv2.waitKey(30) == ord('q'):
            # 현재 반복문을 즉시 종료
            break

    # 카메라·동영상·VideoWriter 자원을 운영체제에 반환
    cap.release()
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
