#
# [핵심 주제]
# 카메라 입력 해상도를 설정
#
# 실시간 로봇 비전에서는 해상도가 매우 중요
#
# 해상도 높음 → 정보 많음, 처리 느림
# 해상도 낮음 → 정보 적음, 처리 빠름
#
# [실습 목표]
# 1. cap.set() 사용법 이해
# 2. 프레임 너비 설정
# 3. 프레임 높이 설정
# 4. 실제 적용된 해상도 확인
#
# [실무에서 자주 하는 실수]
# 실수 1. 설정한 해상도가 반드시 적용된다고 생각함
#
# 카메라가 지원하지 않는 해상도는 적용되지 않을 수 있음
#
# 그래서 반드시 `cap.get()`으로 확인필요
#
# 실수 2. 고해상도만 선호함
#
# 로봇 주행 제어에서는 1920×1080보다 640×480 또는 320×240이 더 적합할 수 있음
#
# 중요한 것은 화질이 아니라 제어에 필요한 정보를 충분히 빠르게 얻는 것임
#
# [ROS2와 연결되는 포인트]
# ROS2 카메라 드라이버에서도 해상도는 파라미터로 설정하는 경우가 많습니다.
#
# width: 640
# height: 480
# fps: 30
#
# OpenCV에서 해상도와 처리 속도의 관계를 이해하면 ROS2 카메라 파라미터 튜닝도 쉬워집니다.
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 웹캠 번호 또는 동영상 파일을 OpenCV 영상 입력으로 열기
cap = cv2.VideoCapture(0)

# 카메라나 동영상 입력이 정상적으로 열렸는지 확인
if not cap.isOpened():
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("카메라를 열 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 카메라의 해상도나 기타 입력 속성을 원하는 값으로 설정
    cap.set(cv2.CAP_PROP_FRAME_WIDTH, 640)
    cap.set(cv2.CAP_PROP_FRAME_HEIGHT, 480)

    # 카메라나 동영상의 속성값을 읽기
    actual_width = cap.get(cv2.CAP_PROP_FRAME_WIDTH)
    actual_height = cap.get(cv2.CAP_PROP_FRAME_HEIGHT)

    # 현재 상태 또는 계산 결과의 터미널 출력
    print("설정된 카메라 너비:", actual_width)
    print("설정된 카메라 높이:", actual_height)

    # 조건이 참인 동안 아래 코드를 계속 반복
    while True:
        # 영상에서 프레임 한 장을 읽고, 성공 여부와 이미지 배열을 각각 수신
        ret, frame = cap.read()

        # 필요한 조건이 충족되지 않았을 때의 처리를 시작함
        if not ret:
            # 현재 상태 또는 계산 결과의 터미널 출력
            print("프레임을 읽을 수 없습니다.")
            # 현재 반복문을 즉시 종료
            break

        # 처리 결과 확인용 OpenCV 창 표시
        cv2.imshow("Resolution Camera", frame)

        # 키 입력 대기 및 실시간 영상 갱신
        if cv2.waitKey(1) == ord('q'):
            # 현재 반복문을 즉시 종료
            break

    # 카메라·동영상·VideoWriter 자원을 운영체제에 반환
    cap.release()
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
