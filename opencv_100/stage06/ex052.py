# [핵심 주제]
# 카메라에서 프레임을 반복적으로 읽어 실시간 영상으로 출력
#
# [실습 목표]
# 1. while 반복문으로 프레임 계속 읽기
# 2. cap.read() 사용법 이해
# 3. cv2.imshow()로 실시간 영상 출력
# 4. waitKey(1)의 의미 이해
#
# [실무에서 자주 하는 실수]
# 실수 1. waitKey를 빼먹음
#
# `imshow()`만 쓰고 `waitKey()`를 빼면 창이 제대로 갱신되지 않을 수 있습니다.
#
# 실수 2. 무한 루프 종료 조건이 없음
#
# 종료 조건이 없으면 창을 닫아도 프로그램이 계속 실행될 수 있음
#
# if cv2.waitKey(1) == ord('q'):
# break
#
# 같은 종료 조건이 필요
#
# [ROS2와 연결되는 포인트]
# ROS2 Subscriber 노드에서는 `while True` 대신 콜백 함수가 프레임을 수신
#
# OpenCV:
# while True:
# cap.read()
#
# ROS2:
# def image_callback(msg):
# frame = bridge.imgmsg_to_cv2(msg)
#
# 즉, 구조는 다르지만 프레임을 받아 처리한다는 핵심은 같습니다.
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 웹캠 번호 또는 동영상 파일을 OpenCV 영상 입력으로 열기
cap = cv2.VideoCapture(0)

# 카메라나 동영상 입력이 정상적으로 열렸는지 확인
if not cap.isOpened():
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("카메라를 열 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 조건이 참인 동안 아래 코드를 계속 반복
    while True:
        # 영상에서 프레임 한 장을 읽고, 성공 여부와 이미지 배열을 각각 수신
        ret, frame = cap.read()

        # 필요한 조건이 충족되지 않았을 때의 처리를 시작함
        if not ret:
            # 현재 상태 또는 계산 결과의 터미널 출력
            print("프레임을 읽을 수 없습니다.")
            # 현재 반복문을 즉시 종료
            break

        # 처리 결과 확인용 OpenCV 창 표시
        cv2.imshow("Camera Frame", frame)

        # 키 입력 대기 및 실시간 영상 갱신
        if cv2.waitKey(1) == ord('q'):
            # 현재 반복문을 즉시 종료
            break

    # 카메라·동영상·VideoWriter 자원을 운영체제에 반환
    cap.release()
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
