#
# [핵심 주제]
# `cv2.VideoCapture()`를 사용하여 웹캠을 엽니다.
#
# OpenCV에서 카메라를 사용할 때 가장 먼저 하는 작업임
#
# [실습 목표]
# 1. cv2.VideoCapture() 사용법 이해
# 2. 기본 카메라 번호 이해
# 3. 카메라 열기 성공 여부 확인
# 4. 카메라 자원 해제 습관 익히기
#
# [실무에서 자주 하는 실수]
# 실수 1. 카메라 번호를 무조건 0으로만 사용
#
# USB 카메라가 여러 개 연결되어 있으면 `0`이 원하는 카메라가 아닐 수 있음
#
# cap = cv2.VideoCapture(1)
#
# 또는
#
# cap = cv2.VideoCapture(2)
#
# 로 테스트해야 할 수 있음
#
# 실수 2. 카메라 해제를 하지 않음
#
# `cap.release()`를 하지 않으면 다른 프로그램에서 카메라를 사용하지 못하는 경우가 있습니다.
#
# [ROS2와 연결되는 포인트]
# ROS2에서는 보통 카메라 드라이버 노드가 카메라를 열기
#
# 일반 OpenCV:
# VideoCapture → frame
#
# ROS2:
# camera driver node → /camera/image_raw
#
# 하지만 ROS2 카메라 노드를 직접 만들 때는 `VideoCapture()` 구조를 이해하고 있어야 함
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 웹캠 번호 또는 동영상 파일을 OpenCV 영상 입력으로 열기
cap = cv2.VideoCapture(0)

# 카메라나 동영상 입력이 정상적으로 열렸는지 확인
if not cap.isOpened():
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("카메라를 열 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("카메라가 정상적으로 열렸습니다.")

# 카메라·동영상·VideoWriter 자원을 운영체제에 반환
cap.release()
