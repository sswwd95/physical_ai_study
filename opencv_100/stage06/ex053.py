# 노션 원문 학습 설명: 예제 53. 키보드 입력으로 종료
# ============================================================================
#
# [핵심 주제]
# 실시간 영상 처리 프로그램에서 키보드 입력을 받아 종료하거나 기능을 전환함
#
# [실습 목표]
# 1. cv2.waitKey() 반환값 이해
# 2. q 키로 종료
# 3. s 키로 상태 메시지 출력
# 4. 키 입력 기반 제어 구조 이해
#
# [실무에서 자주 하는 실수]
# 실수 1. key 값을 저장하지 않고 여러 번 waitKey 호출
#
# 다음 방식은 좋지 않습니다.
#
# if cv2.waitKey(1) == ord('q'):
# break
#
# if cv2.waitKey(1) == ord('s'):
# print("save")
#
# `waitKey()`를 여러 번 호출하면 키 입력 처리가 꼬일 수 있습니다.
#
# 권장 방식은 한 번만 호출하고 변수에 저장하는 것임
#
# key = cv2.waitKey(1)
#
# [ROS2와 연결되는 포인트]
# ROS2 노드에서는 보통 키보드 입력보다 파라미터, 서비스, 토픽으로 상태를 제어함
#
# 하지만 OpenCV 실습 단계에서는 키 입력으로 다음 기능을 테스트하기 좋습니다.
#
# q: 종료
# s: 이미지 저장
# g: Grayscale 모드
# e: Edge 모드
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 웹캠 번호 또는 동영상 파일을 OpenCV 영상 입력으로 열기
cap = cv2.VideoCapture(0)

# 카메라나 동영상 입력이 정상적으로 열렸는지 확인
if not cap.isOpened():
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("카메라를 열 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 조건이 참인 동안 아래 코드를 계속 반복
    while True:
        # 영상에서 프레임 한 장을 읽고, 성공 여부와 이미지 배열을 각각 수신
        ret, frame = cap.read()

        # 필요한 조건이 충족되지 않았을 때의 처리를 시작함
        if not ret:
            # 현재 상태 또는 계산 결과의 터미널 출력
            print("프레임을 읽을 수 없습니다.")
            # 현재 반복문을 즉시 종료
            break

        # 처리 결과 확인용 OpenCV 창 표시
        cv2.imshow("Keyboard Control Camera", frame)

        # 키 입력 대기 및 실시간 영상 갱신
        key = cv2.waitKey(1)

        # 조건이 참일 때만 아래 들여쓰기된 코드를 실행
        if key == ord('q'):
            # 현재 상태 또는 계산 결과의 터미널 출력
            print("q 키 입력: 프로그램 종료")
            # 현재 반복문을 즉시 종료
            break

        # 앞 조건이 거짓일 때 추가 조건을 검사함
        elif key == ord('s'):
            # 현재 상태 또는 계산 결과의 터미널 출력
            print("s 키 입력: 현재 프레임 표시 중")

    # 카메라·동영상·VideoWriter 자원을 운영체제에 반환
    cap.release()
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
