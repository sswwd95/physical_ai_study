# [핵심 주제]
# 카메라 영상 처리 속도인 FPS를 확인
#
# FPS는 Frames Per Second의 약자임
#
# FPS = 1초에 처리하는 프레임 수
#
# 로봇 비전에서는 FPS가 낮으면 제어 반응이 늦어집니다.
#
# [실습 목표]
# 1. time 모듈로 처리 시간 측정
# 2. FPS 계산
# 3. 화면에 FPS 표시
# 4. 처리량과 실시간성 관계 이해
#
# [실무에서 자주 하는 실수]
# 실수 1. FPS만 높으면 좋다고 생각함
#
# FPS가 높아도 검출 정확도가 낮으면 의미가 없음
#
# 실무에서는 다음 균형이 중요
#
# FPS
# 정확도
# 지연시간
# CPU/GPU 사용량
# 제어 안정성
#
# 실수 2. FPS 계산 위치가 잘못됨
#
# 영상 처리 전후 어디에서 시간을 재는지에 따라 FPS가 변화
#
# 실제 처리 성능을 보려면 전처리, 검출, 표시까지 포함한 전체 루프 시간을 재는 것이 좋습니다.
#
# [ROS2와 연결되는 포인트]
# ROS2 비전 노드에서는 FPS가 곧 메시지 발행 주기와 연결됨
#
# 30 FPS → 약 33ms마다 한 프레임
# 10 FPS → 약 100ms마다 한 프레임
# 5 FPS  → 약 200ms마다 한 프레임
#
# 로봇 주행 제어에서는 너무 낮은 FPS가 흔들림이나 반응 지연으로 이어질 수 있음
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2
# 실행 시간이나 FPS를 계산하기 위해 시간 관련 기능을 불러오기
import time

# 웹캠 번호 또는 동영상 파일을 OpenCV 영상 입력으로 열기
cap = cv2.VideoCapture(0)

# 카메라나 동영상 입력이 정상적으로 열렸는지 확인
if not cap.isOpened():
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("카메라를 열 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # prev time 변수에 이후 처리에 사용할 값을 저장
    prev_time = time.time()

    # 조건이 참인 동안 아래 코드를 계속 반복
    while True:
        # 영상에서 프레임 한 장을 읽고, 성공 여부와 이미지 배열을 각각 수신
        ret, frame = cap.read()

        # 필요한 조건이 충족되지 않았을 때의 처리를 시작함
        if not ret:
            # 현재 상태 또는 계산 결과의 터미널 출력
            print("프레임을 읽을 수 없습니다.")
            # 현재 반복문을 즉시 종료
            break

        # current time 변수에 이후 처리에 사용할 값을 저장
        current_time = time.time()
        # elapsed time 변수에 이후 처리에 사용할 값을 저장
        elapsed_time = current_time - prev_time
        # prev time 변수에 이후 처리에 사용할 값을 저장
        prev_time = current_time

        # 조건이 참일 때만 아래 들여쓰기된 코드를 실행
        if elapsed_time > 0:
            # fps 값을 계산하거나 저장해 이후 처리에서 사용
            fps = 1.0 / elapsed_time
        # 앞 조건이 거짓일 때의 실행 구간
        else:
            # fps 값을 계산하거나 저장해 이후 처리에서 사용
            fps = 0

        # 이미지 위에 상태나 좌표 정보를 글자로 표시
        cv2.putText(
            frame,
            f"FPS: {fps:.2f}",
            (20, 40),
            cv2.FONT_HERSHEY_SIMPLEX,
            1.0,
            (0, 255, 0),
            2
        )

        # 처리 결과 확인용 OpenCV 창 표시
        cv2.imshow("FPS Camera", frame)

        # 키 입력 대기 및 실시간 영상 갱신
        if cv2.waitKey(1) == ord('q'):
            # 현재 반복문을 즉시 종료
            break

    # 카메라·동영상·VideoWriter 자원을 운영체제에 반환
    cap.release()
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
