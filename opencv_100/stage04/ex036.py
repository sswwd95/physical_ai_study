# [실습 목표]
# 1. 엣지 보존 필터 개념 이해
# 2. cv2.edgePreservingFilter() 사용법 이해
# 3. 일반 블러와 차이 이해
# 4. 경계를 유지하면서 부드럽게 만드는 효과 확인
#
# [실무에서 자주 하는 실수]
# 실수 1. 실시간 처리에 무조건 사용
#
# 엣지 보존 필터는 일반 Blur보다 계산량이 클 수 있음
#
# 실시간 카메라 노드에서 사용하면 FPS가 떨어질 수 있음
#
# 실수 2. 필터 결과가 좋아 보인다고 검출 성능도 좋아진다고 생각함
#
# 사람 눈에 보기 좋은 이미지와 알고리즘이 처리하기 좋은 이미지는 다를 수 있음
#
# 객체 검출에서는 오히려 단순한 Gaussian Blur + Threshold가 더 안정적일 수 있음
#
# [ROS2와 연결되는 포인트]
# 엣지 보존 필터는 로봇 비전에서 다음처럼 사용 가능
#
# 1. 경계가 중요한 물체 검출
# 2. 작업물 외곽선 유지
# 3. 표면 노이즈 제거
# 4. 검사 영상 전처리
#
# 다만 주행 제어보다는 검사, 인식, 시각화 목적에 더 적합
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 입력 또는 출력 파일 경로 지정
image_path = "practice_images/sample.jpg"

# 지정 경로의 이미지 읽기 및 NumPy 배열 저장
image = cv2.imread(image_path)

# 이미지 또는 검출 결과 생성 여부 확인
if image is None:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 읽을 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 경계선을 보존하거나 세부 표현을 강화하는 필터를 적용
    edge_preserved = cv2.edgePreservingFilter(
        image,
        flags=1,
        sigma_s=60,
        sigma_r=0.4
    )

    # 처리 결과 확인용 OpenCV 창 표시
    cv2.imshow("Original Image", image)
    cv2.imshow("Edge Preserving Filter", edge_preserved)

    # 키 입력 대기 및 실시간 영상 갱신
    cv2.waitKey(0)
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
