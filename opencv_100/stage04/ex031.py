# 쉽게 말하면 이미지의 거친 부분을 부드럽게 만드는 처리임
#
# 주변 픽셀 평균 계산
# → 현재 픽셀 값 대체
# → 이미지가 부드러워짐
#
# [실습 목표]
# 1. 평균 블러 개념 이해
# 2. cv2.blur() 사용법 이해
# 3. 커널 크기 의미 이해
# 4. 블러가 강해질수록 이미지가 흐려지는 이유 이해
#
# [실무에서 자주 하는 실수]
# 실수 1. 커널 크기를 너무 크게 설정함
#
# 예를 들어 다음처럼 하면 이미지가 너무 흐려질 수 있음
#
# blur = cv2.blur(image, (51, 51))
#
# 객체 경계, 라인, 작은 부품이 사라질 수 있음
#
# 실수 2. Edge 검출 전에 무조건 큰 블러 적용
#
# Edge 검출 전에 약한 블러는 노이즈 제거에 도움이 됨
#
# 하지만 너무 강한 블러는 Edge 자체를 약하게 생성
#
# 적당한 블러: 잡음 감소
# 과도한 블러: 경계 정보 손실
#
# [ROS2와 연결되는 포인트]
# ROS2 카메라 영상에서 평균 블러는 다음 상황에 사용 가능
#
# 1. 영상이 너무 거칠 때
# 2. Threshold 전에 작은 밝기 변화 제거
# 3. 색상 마스크의 작은 점 노이즈 완화
# 4. Edge 검출 전 약한 노이즈 제거
#
# 다만 실시간 로봇 제어에서는 계산량과 정보 손실을 함께 고려필요
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 입력 또는 출력 파일 경로 지정
image_path = "practice_images/sample.jpg"

# 지정 경로의 이미지 읽기 및 NumPy 배열 저장
image = cv2.imread(image_path)

# 이미지 또는 검출 결과 생성 여부 확인
if image is None:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 읽을 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 주변 픽셀의 평균값을 사용해 이미지를 부드럽게 생성
    blur_3 = cv2.blur(image, (3, 3))
    blur_7 = cv2.blur(image, (7, 7))
    blur_15 = cv2.blur(image, (15, 15))

    # 처리 결과 확인용 OpenCV 창 표시
    cv2.imshow("Original Image", image)
    cv2.imshow("Average Blur 3x3", blur_3)
    cv2.imshow("Average Blur 7x7", blur_7)
    cv2.imshow("Average Blur 15x15", blur_15)

    # 키 입력 대기 및 실시간 영상 갱신
    cv2.waitKey(0)
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
