# [실무에서 자주 하는 실수]
# 실수 1. uint8 이미지에 바로 음수 노이즈를 더함
#
# `uint8`은 0~255 범위만 표현합니다.
#
# 음수나 255 초과 값이 생기면 의도하지 않은 값으로 변동 가능
#
# 그래서 계산할 때는 `int16` 또는 `float32`로 바꾼 뒤, 마지막에 다시 `uint8`로 변환하는 것이 안전
#
# 실수 2. clip 처리를 하지 않음
#
# 노이즈를 더하면 픽셀 값이 범위를 벗어날 수 있음
#
# 반드시 다음 처리가 필요
#
# np.clip(noisy_image, 0, 255)
