#
# 1. 카메라 노이즈에 강한 알고리즘 테스트
# 2. 조명 변화 대응 실험
# 3. 딥러닝 학습 데이터 증강
# 4. 필터 성능 비교
#
# 실제 로봇 환경은 항상 이상적이지 않기 때문에, 노이즈를 일부러 넣고 알고리즘을 테스트하는 것이 중요
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2
# 이미지 배열 및 수치 계산용 NumPy 불러오기
import numpy as np

# 입력 또는 출력 파일 경로 지정
image_path = "practice_images/sample.jpg"

# 지정 경로의 이미지 읽기 및 NumPy 배열 저장
image = cv2.imread(image_path)

# 이미지 또는 검출 결과 생성 여부 확인
if image is None:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 읽을 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 실습용 노이즈를 만들기 위해 난수를 생성
    noise = np.random.normal(
        loc=0,
        scale=25,
        size=image.shape
    ).astype(np.int16)

    # noisy image 변수에 이후 처리에 사용할 값을 저장
    noisy_image = image.astype(np.int16) + noise
    noisy_image = np.clip(noisy_image, 0, 255)
    noisy_image = noisy_image.astype(np.uint8)

    # 처리 결과 확인용 OpenCV 창 표시
    cv2.imshow("Original Image", image)
    cv2.imshow("Noisy Image", noisy_image)

    # 키 입력 대기 및 실시간 영상 갱신
    cv2.waitKey(0)
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
