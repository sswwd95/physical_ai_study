#
# 밝기 조절은 전체 픽셀 값에 일정 값을 더하거나 빼는 방식으로 이해할 수 있음
#
# 밝게 만들기: 픽셀 값 증가
# 어둡게 만들기: 픽셀 값 감소
#
# [실습 목표]
# 1. 이미지 밝기 개념 이해
# 2. cv2.convertScaleAbs() 사용법 이해
# 3. 밝은 이미지 만들기
# 4. 어두운 이미지 만들기
#
# [실무에서 자주 하는 실수]
# 실수 1. NumPy 덧셈으로 직접 밝기 조절
#
# 다음 코드는 위험할 수 있음
#
# bright_image = image + 50
#
# 이미지 픽셀은 보통 `uint8`임
#
# `uint8`은 0~255 범위만 표현합니다.
#
# 255를 넘으면 값이 이상하게 순환될 수 있음
#
# 예를 들어 250에 50을 더하면 300이 되어야 하지만, `uint8`에서는 이상한 값으로 바뀔 수 있음
#
# 그래서 OpenCV의 `convertScaleAbs()`를 사용하는 것이 안전
#
# 실수 2. 밝기와 대비를 혼동함
#
# 밝기 조절은 보통 `beta`와 관련이 있음
#
# beta 증가 → 밝아짐
# beta 감소 → 어두워짐
#
# 대비 조절은 `alpha`와 관련이 있음
#
# alpha 증가 → 대비 증가
# alpha 감소 → 대비 감소
#
# [ROS2와 연결되는 포인트]
# 로봇 카메라는 실내 조명, 햇빛, 그림자에 영향을 많이 수신
#
# 밝기 보정은 다음 작업 전에 사용 가능
#
# 1. 라인 검출
# 2. 색상 마스크 생성
# 3. Edge 검출
# 4. 객체 인식 전처리
#
# 하지만 밝기 조절을 너무 강하게 하면 색상 정보가 왜곡될 수 있으므로 주의필요
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 입력 또는 출력 파일 경로 지정
image_path = "practice_images/sample.jpg"

# 지정 경로의 이미지 읽기 및 NumPy 배열 저장
image = cv2.imread(image_path)

# 이미지 또는 검출 결과 생성 여부 확인
if image is None:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 읽을 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 픽셀값이 0~255 범위를 벗어나지 않도록 안전하게 밝기·대비를 조절함
    bright_image = cv2.convertScaleAbs(image, alpha=1.0, beta=50)
    dark_image = cv2.convertScaleAbs(image, alpha=1.0, beta=-50)

    # 처리 결과 확인용 OpenCV 창 표시
    cv2.imshow("Original Image", image)
    cv2.imshow("Bright Image", bright_image)
    cv2.imshow("Dark Image", dark_image)

    # 키 입력 대기 및 실시간 영상 갱신
    cv2.waitKey(0)
    # 모든 OpenCV 이미지 창 닫기
    cv2.destroyAllWindows()
