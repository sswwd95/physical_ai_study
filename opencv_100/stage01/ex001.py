# [핵심 주제]
# OpenCV가 정상 설치되었는지 확인하고, 현재 사용하는 OpenCV 버전을 출력
#
# ROS2 Humble에서 카메라 영상을 처리할 때 Python OpenCV를 자주 사용
#
# 따라서 가장 먼저 해야 할 일은 OpenCV가 제대로 import 되는지 확인하는 것임
#
# [실습 목표]
# 이 예제를 통해 다음을 배웁니다.
#
# 1. cv2 모듈 import 방법
# 2. OpenCV 버전 확인 방법
# 3. Python 실행 환경 점검 방법
# 4. ROS2 비전 노드 작성 전 기본 확인 절차
#
# [실무에서 자주 하는 실수]
# 실수 1. opencv-python을 설치하지 않음
#
# ModuleNotFoundError: No module named 'cv2'
#
# 이 오류가 나오면 OpenCV가 설치되지 않은 것임
#
# 일반 Python 환경에서는 다음과 같이 설치함
#
# pip install opencv-python
#
# 이미지 표시 기능까지 사용하는 일반 실습 환경에서는 보통 `opencv-python`을 사용
#
# 실수 2. 파일 이름을 cv2.py로 저장함
#
# 초보자가 자주 하는 실수임
#
# cv2.py
#
# 이런 파일명으로 저장하면 Python이 실제 OpenCV 모듈이 아니라 사용자가 만든 `cv2.py` 파일을 먼저 읽기 가능
#
# 권장 파일명은 다음과 같습니다.
#
# ex01_check_opencv.py
#
# [ROS2와 연결되는 포인트]
# ROS2에서 카메라 영상을 다룰 때 보통 다음 흐름을 사용
#
# 카메라 센서
# → ROS2 Image 메시지
# → cv_bridge
# → OpenCV 이미지
# → 영상 처리
# → 결과 Publish
#
# 따라서 `cv2`가 정상적으로 동작하지 않으면 ROS2 비전 노드도 제대로 동작하지 않습니다.
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 현재 상태 또는 계산 결과의 터미널 출력
print("OpenCV 설치 확인")
print("OpenCV 버전:", cv2.__version__)
