#
# ROI는 Region Of Interest의 약자임
#
# ROI = 관심 영역
#
# 로봇 비전에서는 전체 이미지를 모두 처리하지 않고 필요한 부분만 잘라서 처리하는 경우가 많습니다.
#
# [실습 목표]
# 1. ROI 개념 이해
# 2. 이미지 일부 영역 자르기
# 3. 잘라낸 영역 화면 출력
# 4. 잘라낸 영역 저장
#
# [실무에서 자주 하는 실수]
# 실수 1. ROI 범위가 이미지 크기를 넘어감
#
# 이미지 크기가 다음과 같다고 가정함
#
# height = 480
# width = 640
#
# 이때 다음 코드는 위험함
#
# roi = image[400:700, 500:900]
#
# 이미지 범위를 넘어서기 때문임
#
# 안전하게 하려면 이미지 크기를 먼저 확인필요
#
# height, width = image.shape[:2]
#
# 실수 2. ROI가 원본 이미지의 view라는 점을 모름
#
# NumPy 슬라이싱으로 만든 ROI는 원본 이미지와 메모리를 공유할 수 있음
#
# 예를 들어 다음처럼 하면,
#
# roi = image[100:300, 200:500]
# roi[:, :] = (0, 0, 255)
#
# 원본 이미지의 해당 영역도 빨간색으로 바뀔 수 있음
#
# 원본과 독립적으로 사용하려면 다음처럼 복사함
#
# roi = image[100:300, 200:500].copy()
#
# [ROS2와 연결되는 포인트]
# ROI는 로봇 비전에서 매우 중요
#
# 예를 들어 자율주행 로봇의 카메라 영상 전체는 다음처럼 보일 수 있음
#
# 상단: 벽, 사람, 조명
# 중앙: 장애물
# 하단: 바닥, 라인
#
# 라인 트레이싱을 할 때는 전체 이미지가 아니라 아래쪽 영역만 보면 됨
#
# roi = frame[height//2:height, :]
#
# 이렇게 하면 계산량이 줄고, 불필요한 영역에 의한 오검출도 감소
#
