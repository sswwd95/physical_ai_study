#
# [실무에서 자주 하는 실수]
# 실수 1. image[x, y]로 접근함
#
# 좌표를 생각할 때는 보통 `x, y` 순서이지만, NumPy 배열은 `행, 열` 순서임
#
# 따라서 이미지 배열에서는 다음이 맞습니다.
#
# image[y, x]
#
# 틀린 예:
#
# image[x, y]
#
# 실수 2. 이미지 범위를 벗어난 좌표 접근
#
# 이미지 크기가 다음과 같다고 가정함
#
# height = 480
# width = 640
#
# 가능한 좌표 범위는 다음임
#
# x: 0 ~ 639
# y: 0 ~ 479
#
# 그런데 다음처럼 접근하면 오류가 날 수 있음
#
# pixel = image[500, 700]
#
# [ROS2와 연결되는 포인트]
# 로봇 비전에서 픽셀 값 읽기는 다음 작업의 기본임
#
# 1. 특정 위치의 색상 확인
# 2. 라인 트레이싱에서 중앙 픽셀 검사
# 3. 카메라 영상의 장애물 색상 확인
# 4. 객체 중심점 주변 색상 분석
#
# 예를 들어 라인트레이싱 로봇에서는 화면 아래쪽 중앙 픽셀의 색을 확인하여 주행 방향을 결정할 수 있음
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 입력 또는 출력 파일 경로 지정
image_path = "practice_images/sample.jpg"

# 지정 경로의 이미지 읽기 및 NumPy 배열 저장
image = cv2.imread(image_path)

# 이미지 또는 검출 결과 생성 여부 확인
if image is None:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 읽을 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # y 변수에 이후 처리에 사용할 값을 저장
    y = 100
    # x 변수에 이후 처리에 사용할 값을 저장
    x = 150

    # pixel 변수에 이후 처리에 사용할 값을 저장
    pixel = image[y, x]

    # 현재 상태 또는 계산 결과의 터미널 출력
    print("좌표 x:", x)
    print("좌표 y:", y)
    print("픽셀 BGR 값:", pixel)

    # blue 변수에 이후 처리에 사용할 값을 저장
    blue = pixel[0]
    # green 변수에 이후 처리에 사용할 값을 저장
    green = pixel[1]
    # red 변수에 이후 처리에 사용할 값을 저장
    red = pixel[2]

    # 현재 상태 또는 계산 결과의 터미널 출력
    print("Blue:", blue)
    print("Green:", green)
    print("Red:", red)
