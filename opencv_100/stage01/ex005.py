# OpenCV 이미지는 NumPy 배열이므로 `shape`, `dtype`, `size`를 확인 가능
#
# [실습 목표]
# 1. 이미지의 높이 확인
# 2. 이미지의 너비 확인
# 3. 채널 수 확인
# 4. 픽셀 데이터 타입 확인
# 5. 전체 픽셀 개수 확인
#
# [실무에서 자주 하는 실수]
# 실수 1. width와 height 순서를 헷갈림
#
# OpenCV 이미지의 `shape` 순서는 다음임
#
# height, width, channels
#
# 하지만 좌표를 다룰 때는 보통 다음 순서를 씁니다.
#
# x, y
#
# 즉,
#
# x는 width 방향
# y는 height 방향
#
# 초보자가 매우 자주 헷갈립니다.
#
# 실수 2. 흑백 이미지에서 channels를 꺼내려 함
#
# 흑백 이미지는 보통 `shape`가 다음처럼 출력
#
# (480, 640)
#
# 즉, 채널 값이 없음
#
# 그런데 다음처럼 작성하면 오류가 납니다.
#
# height, width, channels = gray.shape
#
# 흑백 이미지는 다음처럼 처리필요
#
# height, width = gray.shape
#
# [ROS2와 연결되는 포인트]
# ROS2 카메라 메시지를 처리할 때도 이미지 크기와 채널 수를 확인필요
#
# 예를 들어 로봇 카메라에서 들어오는 이미지가 다음과 같을 수 있음
#
# 640 × 480 RGB
# 1280 × 720 BGR
# 320 × 240 Grayscale
#
# 이미지 크기를 모르면 객체 중심 좌표를 계산하거나 주행 제어로 연결할 때 오류가 발생함
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 입력 또는 출력 파일 경로 지정
image_path = "practice_images/sample.jpg"

# 지정 경로의 이미지 읽기 및 NumPy 배열 저장
image = cv2.imread(image_path)

# 이미지 또는 검출 결과 생성 여부 확인
if image is None:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 읽을 수 없습니다.")
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지 shape:", image.shape)
    print("이미지 dtype:", image.dtype)
    print("이미지 size:", image.size)

    # 이미지 배열의 높이, 너비, 채널 수 같은 크기 정보를 가져옵니다.
    height, width, channels = image.shape

    # 현재 상태 또는 계산 결과의 터미널 출력
    print("높이:", height)
    print("너비:", width)
    print("채널 수:", channels)
