#
# 실수 2. 한글 경로 또는 공백 경로 문제
#
# Windows 환경에서는 다음과 같은 경로가 문제를 일으키는 경우가 있음
#
# C:/Users/홍길동/바탕 화면/이미지/sample.jpg
#
# 초보자 실습에서는 가능하면 다음처럼 단순한 영문 경로를 권장함
#
# C:/opencv_practice/images/sample.jpg
#
# [ROS2와 연결되는 포인트]
# ROS2 카메라 노드에서는 실제 이미지 파일 대신 카메라 프레임을 수신
#
# 하지만 처리 구조는 비슷함
#
# 이미지 파일 읽기
# → NumPy 배열
# → OpenCV 처리
#
# ROS2에서는 다음 흐름이 됨
#
# ROS2 Image 메시지 수신
# → cv_bridge로 변환
# → NumPy 배열
# → OpenCV 처리
#
# 즉, `cv2.imread()`는 ROS2 비전 처리의 가장 기초가 되는 이미지 구조를 이해하는 데 좋습니다.
# ============================================================================
# OpenCV 기능 사용을 위한 cv2 모듈 불러오기
import cv2

# 입력 또는 출력 파일 경로 지정
image_path = "practice_images/sample.jpg"

# 지정 경로의 이미지 읽기 및 NumPy 배열 저장
image = cv2.imread(image_path)

# 이미지 또는 검출 결과 생성 여부 확인
if image is None:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 읽을 수 없습니다.")
    print("파일 경로를 확인하세요:", image_path)
# 앞 조건이 거짓일 때의 실행 구간
else:
    # 현재 상태 또는 계산 결과의 터미널 출력
    print("이미지를 성공적으로 읽었습니다.")
    print("이미지 데이터 타입:", type(image))
